"""Check that the installed torch matches the torch the extension was built for.

The compiled extension only works with the torch minor version and the CUDA major
version it was built against. Without this check, a mismatch shows up as an
``ImportError: ... undefined symbol`` when loading ``phipict._C``.
"""

from __future__ import annotations

import importlib

import torch

WHEEL_INDEX_URL = "https://upb-sciml.github.io/phiPICT/whl/"
BUILD_FROM_SOURCE_URL = (
    "https://upb-sciml.github.io/phiPICT/docs/installation.html#building-from-source"
)


def _torch_minor(version: str) -> str:
    return ".".join(version.split("+")[0].split(".")[:2])


def _cuda_major(version: str | None) -> str | None:
    return None if version is None else version.split(".")[0]


def check_build() -> None:
    """Raise an ImportError if the installed torch does not match the build.

    Does nothing if the build information is missing, e.g. when the docs are
    built without compiling the extension.
    """
    try:
        # Generated by setup.py, so it does not exist in a plain source checkout
        info = importlib.import_module("phipict._build_info")
    except ImportError:
        return
    built_torch: str = info.TORCH_VERSION
    built_cuda: str | None = info.CUDA_VERSION

    torch_minor = _torch_minor(torch.__version__)
    torch_cuda = torch.version.cuda
    if torch_minor == built_torch and _cuda_major(torch_cuda) == _cuda_major(
        built_cuda
    ):
        return

    built = f"PyTorch {built_torch} with CUDA {built_cuda}"
    if torch_cuda is None:
        installed = f"PyTorch {torch.__version__} without CUDA"
        fix = (
            "phiPICT needs a CUDA build of PyTorch. Reinstall phiPICT with "
            "'pip install --force-reinstall phipict' to get the PyTorch it was "
            "built for."
        )
    else:
        installed = f"PyTorch {torch.__version__} with CUDA {torch_cuda}"
        page = f"{WHEEL_INDEX_URL}torch-{torch_minor}+cu{_cuda_major(torch_cuda)}.html"
        fix = (
            "Install the phiPICT wheel for your PyTorch (if it exists in the wheel "
            f"index {WHEEL_INDEX_URL}):\n\n"
            "    pip install --force-reinstall --no-deps --no-index "
            f"-f {page} phipict\n\n"
            "or reinstall the PyPI default together with its PyTorch "
            "('pip install --force-reinstall phipict'), or build phiPICT from "
            f"source against your PyTorch: {BUILD_FROM_SOURCE_URL}"
        )
    raise ImportError(
        f"phiPICT was built for {built}, but {installed} is installed. The compiled "
        "extension only works with the PyTorch minor version and CUDA major version "
        f"it was built for. {fix}"
    )


# Runs on import, before phipict/__init__.py loads the extension
check_build()
